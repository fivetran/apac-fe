-- Read-only. Null coverage with zero rows means no data, not healthy pipelines.
SELECT 'LOG' AS source_table, COUNT(*) AS recorded_rows,
       TO_VARCHAR(MIN(TIME_STAMP)) AS first_observed, TO_VARCHAR(MAX(TIME_STAMP)) AS last_observed,
       TO_VARCHAR(MAX(_FIVETRAN_SYNCED)) AS newest_row_landed
FROM NAAG_POSTGRES.NAAG_FIVETRAN_LOG.LOG
UNION ALL
SELECT 'INCREMENTAL_MAR', COUNT(*), TO_VARCHAR(MIN(MEASURED_DATE)), TO_VARCHAR(MAX(MEASURED_DATE)),
       TO_VARCHAR(MAX(_FIVETRAN_SYNCED))
FROM NAAG_POSTGRES.NAAG_FIVETRAN_LOG.INCREMENTAL_MAR
UNION ALL
SELECT 'AUDIT_TRAIL', COUNT(*), TO_VARCHAR(MIN(CAPTURED_AT)), TO_VARCHAR(MAX(CAPTURED_AT)), NULL
FROM NAAG_POSTGRES.NAAG_FIVETRAN_LOG.AUDIT_TRAIL;
